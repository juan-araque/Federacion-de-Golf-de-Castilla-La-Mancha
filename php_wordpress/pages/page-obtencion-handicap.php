    <p>3. Si el jugador supera la prueba teórica, la Federación Autonómica validará el handicap otorgado por el profesor y lo tramitará a la Real Federación Española de Golf. En caso de no superar la prueba, podrá repetirla en dos ocasiones más.</p>

