    <div class="block-title">Cobertura de las pólizas</div>

    <p>Estas pólizas de seguros cubren los <strong>accidentes</strong> de los federados (046557680) sufridos con motivo de la práctica deportiva y la <strong>responsabilidad civil</strong> (046540082) que dichos federados causen con motivo de dicha práctica. Todo ello, en los términos previstos por el Real Decreto 849/1993.</p>

    <h3>Póliza de accidentes (046557680)</h3>
    <p>Se entiende por accidente los traumatismos puntuales, violentos, súbitos, externos y ajenos a la intencionalidad del federado, sufridos durante la práctica deportiva (incluidos los producidos como conductores de buggies), siempre que no sean debidos a lesiones crónicas y/o preexistentes, enfermedades o patologías crónicas derivadas de la práctica habitual del deporte, microtraumatismos repetidos, tendinitis, bursitis crónica, artrosis o artritis, hernias discales, y en general, cualquier patología degenerativa.</p>
    <p>Tendrán la consideración de accidente los infartos de miocardio y las anginas de pecho sufridos por los federados, siempre que éstos se produzcan en el campo de juego durante la práctica deportiva o, subsiguientemente a ésta, en las instalaciones del club o recinto deportivo.</p>
    <p>Quedan cubiertos los accidentes sufridos por los federados <strong>conductores</strong> de un buggie de golf.</p>
    <p><strong>Para el acceso a las coberturas es NECESARIO seguir las indicaciones del PROTOCOLO DE ACTUACIÓN EN CASO DE ACCIDENTES.</strong></p>

    <h3>Póliza de responsabilidad civil (046540082)</h3>
    <p>Estarán cubiertos los federados frente a posibles reclamaciones de terceros por daños – corporales o materiales – causados con motivo de la práctica deportiva en un club federado u oficial, en cualquier lugar del mundo (dentro de los límites económicos suscritos), quedando expresamente excluidos los derivados del uso de vehículos a motor incluidos los coches de golf.</p>
    <p><strong>No serán terceros</strong> a efectos de la cobertura, las personas que, respecto del federado causante, sean cónyuges o familiares consanguíneos o afines, hasta segundo grado, o empleados en el desarrollo de las funciones propias de su cometido.</p>
    <p><strong>Para el acceso a las coberturas es NECESARIO seguir las indicaciones del PROTOCOLO DE ACTUACIÓN DE RESPONSABILIDAD CIVIL.</strong></p>

    <h3>Buggies y coches de golf</h3>
    <p>Recordamos a todos los Clubes/Campos de Golf e instalaciones deportivas federadas que la responsabilidad civil causada con motivo de la conducción/utilización de los buggies/coches de golf <strong>NO</strong> está incluida en estas pólizas, motivo por el que <strong>RECOMENDAMOS que aquellos que los tengan en propiedad, en régimen de renting o leasing, procedan a suscribir una PÓLIZA DE SEGUROS</strong> que cubra la responsabilidad que conlleva dicha utilización/uso.</p>

    <h3>Información y difusión</h3>
    <p>Toda la información podrán consultarla en la sección correspondiente del portal Web de la RFEG: <a href="https://www.rfegolf.es/default.aspx" target="_blank" style="color:var(--green-accent);font-weight:600;text-decoration:none;">www.rfegolf.es</a></p>
    <p>Rogamos a los clubes <strong>procedan a colocar toda la información en sus tablones de anuncio</strong> para conocimiento de todos los federados.</p>

    <h3>Fraudes / Estadísticas</h3>
    <p>Al objeto de la prevención de posibles fraudes que encarezcan las pólizas a los federados y además por motivos estadísticos, ALLIANZ llevará a cabo un registro del número de partes tramitados. Por este motivo es <strong>OBLIGATORIO PARA LOS CLUBES/CAMPOS DE GOLF E INSTALACIONES DEPORTIVAS FEDERADAS, CONSERVAR LOS PARTES TRAMITADOS</strong>, al menos durante <strong>UN AÑO</strong>, después de la comunicación del mismo a la Cía. aseguradora.</p>
